def fix(html):
    """반환 (고친 html, {규칙: 바꾼 개수})"""
    head, sep, body = html.partition("</head>")
    rep = {}
    for pat, new in RULES:
        body, n = re.subn(pat.replace(" · ", "[  ]·[  ]"), new, body)  # 기본틀은 ' · ' 앞에 줄바꿈 없는 공백을 씀
        if n:
            rep[pat[:28]] = n
    return head + sep + body, rep


def text_of(html):
    b = re.sub(r"<style.*?</style>|<script.*?</script>", "", html, flags=re.S)
    b = re.sub(r"<[^>]+>", " ", b).replace("⁠", "").replace(" ", " ")
    return re.sub(r"\s+", " ", b)


def residue(html):
    t = text_of(html)
    return [t[max(0, m.start() - 30):m.end() + 20] for p in BAD for m in re.finditer(p, t)]
