"""업성 마무리 문구 — light_build.eo_final 마지막에 부름(디자인 레이어 · 공용 틀이 넣는 문구까지).
신분평 확인본 검증(검증보고_1101.md) G1 ~ G7 · D1 ~ D13이 복제본에 따라오지 않게 처음부터 고친다. 빠진 문구가 있으면(빌더 문구가 바뀌어 안 맞으면) 멈춘다."""
import re

S = "[\\s ⁠]*·[\\s ⁠]*"

FIX = [  # (지금 문구, 바꿀 문구) — ' · '는 nbsp · 단어 결합자 무시
    # G7: 누적 수임 카드 아래에 주관 실적 숫자를 섞지 않음(수임 ≠ 주관)
    ("2023년 이후 1,000세대 이상 주관 10곳 + 입주 예정 2곳.", "전신 실적 · 입주 예정 포함 누적 수임(주관 실적과 구분)."),
    # D1: 전문 인력 = 전기 · 도장 · 조경 · 간호사 4개 분야 · 응급 대응은 구급요원 · 119(박람회 안전 쪽과 같게)
    ("박람회 현장 응급 대응 지원", "박람회 현장 보건 · 안내 지원(응급은 구급요원 · 119 연계)"),
    # D2: 세스코 협약 만료일이 입주 전으로 보이지 않게(불리한 사실 먼저 노출 금지)
    ("세스코 MOU 2025.11 체결 · 2026.12 갱신 예정.", "세스코 MOU 2025.11 체결 · 입주 시점 적용은 협약 갱신 후 확정."),
    ("세스코 업무협약 2025.11.11 ~ 2026.12.31 ·", "세스코 업무협약 2025.11 체결 · 입주 시점 적용은 협약 갱신 후 확정 ·"),
    # D7: 영주자이(2026.12 입주 · 2026.08 개최) = 박람회 개최 기준
    ("최근 3년(입주 2023.10 ~ 2026.12) 500세대 이상", "최근 3년(박람회 개최 기준 · 입주 2023.10 ~ 2026.12) 500세대 이상"),
    # 업성 제출서류 번호 = 7항 가 ~ 아
    ("2026.10.23 발급본은 제출서류 2", "2026.10.23 발급본은 제출서류 가"),
    ("2026.10.23 발급본은 제출서류 3", "2026.10.23 발급본은 제출서류 가"),
    # 사전점검 영상 = 선택 항목 B 없음(업성 세대 혜택 = 세대 품목만)
    ("점검 요령 영상은 선택 항목 B 세미나 영상", "점검 요령 영상은 협의회 요청 시"),
    # 타 단지 집행 예 — '전 세대' 약속으로 읽히지 않게
    ("전 세대 도어록 무상 업그레이드", "도어록 업그레이드(타 단지 집행 예)"),
]
RX = [  # (정규식, 바꿀 문구)
    # G2: 주관 창구 끝 = 사후관리 기간 종료일(공고 1항 바 · 환불 규정 제10조와 같게)
    (r"협약 종료일\((?:품목별 )?(?:공동구매 )?무상 A/S (?:보증 )?만료일 중 가장 늦은 날\)", "사후관리 기간 종료일(품목별 무상 A/S 만료일)"),
    # 10배 보상 = 1건당 최대 50만원 고정(양보안 먼저 노출 금지)
    (r"[\s ⁠]*·[\s ⁠]*최대 금액은 (?:입예협|협의회)과 협의", ""),
    (r"[\s ⁠]*·[\s ⁠]*NICE 보고서 종업원 5명은 2026\.05 기준", ""),
    (r"에스크로\(예치금\) 약정서", "예치금 약정서"),
    # G4: 업체 심사 = 공구 이력 또는 동종 시공 실적(지역 업체는 시공 실적으로 갈음 · 천안 · 아산권 우선과 맞춤)
    (r"타단지 공구이력 20회 이상", "타단지 공구 이력 또는 동종 시공 실적"),
    (r"타 단지 공동구매 <em>20회</em> 이상 진행", "타 단지 공동구매 이력 또는 동종 시공 실적(지역 업체는 시공 실적으로 갈음)"),
]
GONE = ["20회 이상", "가장 늦은 날", "최대 금액은", "최대액 협의", "입주 예정 2곳", "5개 분야", "2026.12 갱신", "2026.12.31", "선택 항목 B", "B 항목", "협의회 업무지원",
        "단지지원 컨설팅", "2028.05", "2028년", "10억", "제출서류 2", "제출서류 3", "제출서류 4", "제출서류 5", "제출서류 6", "제출서류 8", "제출서류 9", "서류 10",
        "공고 바 ", "공고 라 ", "공고 다 ", "공고 자 ", "공고 차 ", "청주", "신분평", "평가표", "직영 지사", "등기 완료", "현장 공개", "현장 제시",
        "패키지", "발전지원", "에스크로(예치금)", "전 세대 1,460", "30일 안 전담 PM", "선정 후 30일"]
HIT = {}


def _loose(a_):
    return re.escape(a_).replace("\\ ·\\ ", S).replace("\\ ", "[\\s ]+")


def fix(doc):
    for a_, b_ in RX:
        doc, k = re.subn(a_, b_, doc)
        HIT["RX:" + a_] = HIT.get("RX:" + a_, 0) + k
    for a_, b_ in FIX:
        doc, k = re.subn(_loose(a_), lambda m: b_, doc)
        HIT[a_] = HIT.get(a_, 0) + k
    t = re.sub(r"<[^>]+>", " ", re.sub(r"<style.*?</style>|<script.*?</script>", "", doc, flags=re.S))
    t = re.sub(r"[\s ⁠]+", " ", t)
    left = [(bad, re.findall(r".{0,30}" + re.escape(bad) + r".{0,20}", t)[:2]) for bad in GONE
            if bad.replace(" · ", " ") in t.replace(" · ", " ").replace("·", " ")]
    for x in left:
        print("[eo_fix] 남은 문구", x)
    assert not left, ("업성 마무리 문구 남음", [x[0] for x in left])
    return doc


def report():
    miss = [a for a, _ in FIX if not HIT.get(a)] + [a for a, _ in RX if not HIT.get("RX:" + a)]
    print("[eo_fix] 마무리 문구 반영", sum(HIT.values()), "곳 · 안 맞은 문구", len(miss), miss)
    assert not miss, ("업성 마무리 문구가 빌더와 안 맞음", miss)
    return miss
