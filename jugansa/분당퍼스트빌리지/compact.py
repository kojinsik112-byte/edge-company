    k["body"] = sub(k["body"], "협약 시 성명 · 연락처 제출 · ⟦PM 후보 · 팀장급 2 ~ 3명 경력 연수 · 주요 현장(실명 없이)⟧",
                    "전담 PM 성명 · 연락처는 협약 시 제출")

    # p86 → p87: '입주까지 28개월' 장의 변경 기준 약속을 추진 일정 KEY POINT 소문구로
