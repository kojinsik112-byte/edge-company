    miss = [a for a, _ in FIX + (FIX_SALE if sale else []) if not HIT.get(a)]
    print("[cj_fix] 10-30 법정 정밀판 반영", sum(HIT.values()), "곳 · 안 맞은 문구", len(miss), miss)
    assert not miss, ("청주 법정 문구가 빌더와 안 맞음", miss)
    return miss
