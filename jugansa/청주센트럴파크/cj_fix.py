def _loose(a_):
    return re.escape(a_).replace("\\ ·\\ ", S).replace("\\ ", "[\\s ]+")


def fix(doc, sale=True):
    for a_, b_ in FIX + (FIX_SALE if sale else []):
        doc, k = re.subn(_loose(a_), lambda m: b_, doc)
        HIT[a_] = HIT.get(a_, 0) + k
    t = re.sub(r"[\s ⁠]+", " ", re.sub(r"<style.*?</style>|<script.*?</script>", "", doc, flags=re.S))
    for bad in GONE + (GONE_SALE if sale else []):
        assert bad.replace(" · ", " ") not in t.replace(" · ", " ").replace("·", " "), ("청주 10-30 법정 문구 남음", bad, re.findall(r".{0,30}" + re.escape(bad) + r".{0,20}", t)[:3])
    return doc


