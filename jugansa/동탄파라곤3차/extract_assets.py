def save(im, name):
    im = im.convert("RGB")
    if im.width > MAXW:
        im = im.resize((MAXW, round(im.height * MAXW / im.width)), Image.LANCZOS)
    im.save(os.path.join(OUT, name + ".jpg"), quality=86)


def raw_image(doc, page, bbox):
    hits = [b for b in doc[page].get_image_info(xrefs=True)
            if b["xref"] and all(abs(a - c) <= 1.5 for a, c in zip(b["bbox"], bbox))]
    if not hits:
        raise LookupError((page, bbox))
    pix = fitz.Pixmap(doc, hits[0]["xref"])
    if pix.n - pix.alpha > 3:
        pix = fitz.Pixmap(fitz.csRGB, pix)
    mode = "RGBA" if pix.alpha else "RGB"
    im = Image.frombytes(mode, (pix.width, pix.height), pix.samples)
    if pix.alpha:  # 투명 배경은 흰색으로
        bg = Image.new("RGB", im.size, "white")
        bg.paste(im, mask=im.split()[3])
        im = bg
    return im


def main(src):
    os.makedirs(OUT, exist_ok=True)
    doc = fitz.open(src)
    n = 0
    for name, items in PICK.items():
        for k, (page, bbox) in enumerate(items, 1):
            save(raw_image(doc, page, bbox), f"{name}_{k}")
            n += 1
    for name, (page, rect) in CLIP.items():
        pix = doc[page].get_pixmap(dpi=200, clip=fitz.Rect(rect))
        save(Image.open(io.BytesIO(pix.tobytes("png"))), name)
        n += 1
    print(f"{n}장 → {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
