def renumber(body):
    """rows 블록 번호(01, 02…)를 지운 행 뒤에 다시 매긴다."""
    import re
    n = iter(range(1, 100))
    return re.sub(r'<div class="no">\d+</div>', lambda m: f'<div class="no">{next(n):02d}</div>', body)
